"""Build a clean, self-contained copy of the project for transfer (code, config, data, results).

Leaves out secrets, local tooling, OS clutter and regenerable bulk (page images, response cache,
degraded test PDFs), then scans every text file in the bundle for API keys, e-mail addresses and
home-directory paths and FAILS if any are found. Writes BUNDLE_MANIFEST.json with a sha256 per file.

Usage:  uv run python scripts/export_bundle.py [--out dist]
"""

import argparse
import fnmatch
import hashlib
import json
import re
import shutil
import sys
import zipfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

INCLUDE = [
    "README.md", "WORKPLACE.md", "credit-agreement-extraction-HANDOVER.md", "docs/**",
    "pyproject.toml", "uv.lock", "requirements-prod.txt", "models.yaml", ".gitignore",
    "src/**", "tests/**", "scripts/**", "prompts/**", "dictionary/**",
    "data/sec/albemarle-2022-AR.pdf", "data/sec/SHA256SUMS", "data/sec/Document_pages_1-10_extracted.txt",
    "data/golden/**",
    # results
    "var/store/runs/**", "var/store/reports/**", "var/store/records/**", "var/store/ocr/**",
    "var/store/pages/**/manifest.json",  # small; page images themselves are regenerated by `cae ingest`
    "var/handoff/**", "var/audit/**", "var/review-*.csv",
]
EXCLUDE = [".env", ".env.*", "**/.DS_Store", "**/__pycache__/**", "**/*.pyc", ".pytest_cache/**", ".venv/**",
           "var/store/pages/**/*.png", "var/store/cache/**", "data/**/*.degraded-*.pdf", "dist/**"]
# The source PDF's content-addressed copy is kept so grounding can re-read its text layer.
EXTRA_BLOBS = ["data/sec/albemarle-2022-AR.pdf"]

LEAKS = {
    "API key": re.compile(r"sk-ant-[A-Za-z0-9_\-]{10,}|\bsk-[A-Za-z0-9]{32,}\b|\bAKIA[0-9A-Z]{16}\b"),
    "e-mail address": re.compile(r"\b[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}\b"),
    "home-directory path": re.compile(r"/Users/[^/\s\"']+|/home/[^/\s\"']+|[A-Za-z]:\\\\Users\\\\"),
}
SELF = "scripts/export_bundle.py"  # holds the patterns themselves


def document_emails() -> set[str]:
    """E-mail addresses printed in the source agreements (e.g. a notices schedule). They are part of the
    public document, so OCR / extractions of it may contain them; any OTHER address still fails."""
    from credit_extract.ocr import text_layer

    found = set()
    for pdf in (ROOT / "data" / "sec").glob("*.pdf"):
        if ".degraded-" in pdf.name:
            continue
        for page in text_layer(pdf):
            found |= {m.group(0).lower() for m in LEAKS["e-mail address"].finditer(page)}
    return found


def selected() -> list[Path]:
    files = set()
    for pattern in INCLUDE:
        # "dir/**" means every file under dir (Path.glob("dir/**") alone yields only directories)
        globs = [pattern, pattern + "/*"] if pattern.endswith("**") else [pattern]
        for g in globs:
            files |= {p for p in ROOT.glob(g) if p.is_file()}
    rel = lambda p: p.relative_to(ROOT).as_posix()
    return sorted(p for p in files if not any(fnmatch.fnmatch(rel(p), x) for x in EXCLUDE))


def blob_for(pdf: Path) -> Path | None:
    sha = hashlib.sha256(pdf.read_bytes()).hexdigest()
    p = ROOT / "var" / "store" / "blobs" / sha[:2] / f"{sha}.pdf"
    return p if p.exists() else None


def scan(path: Path, arc: str, allowed_emails: set[str]) -> list[str]:
    if arc == SELF or path.suffix in {".pdf", ".png", ".zip"} or path.stat().st_size > 20_000_000:
        return []
    try:
        text = path.read_text(errors="ignore")
    except OSError:
        return []
    hits = []
    for label, rx in LEAKS.items():
        for m in rx.finditer(text):
            # OCR can clip a character ("achary.vestal@..."): allowed if part of a document address
            if label == "e-mail address" and any(m.group(0).lower() in e for e in allowed_emails):
                continue
            hits.append(f"{arc}: {label}: {m.group(0)[:40]}")
    return hits


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="dist")
    args = ap.parse_args()
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d")
    dest = ROOT / args.out / f"credit-extract-{stamp}"
    if dest.exists():
        shutil.rmtree(dest)
    files = [(p, p.relative_to(ROOT).as_posix()) for p in selected()]
    for pdf in EXTRA_BLOBS:
        if (b := blob_for(ROOT / pdf)) is not None:
            files.append((b, b.relative_to(ROOT).as_posix()))

    allowed = document_emails()
    leaks = [h for p, arc in files for h in scan(p, arc, allowed)]
    if leaks:
        print("NOT EXPORTED — remove these first:\n  " + "\n  ".join(leaks[:50]))
        return 1

    manifest = {}
    for src, arc in files:
        target = dest / arc
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, target)
        manifest[arc] = hashlib.sha256(src.read_bytes()).hexdigest()
    (dest / "BUNDLE_MANIFEST.json").write_text(json.dumps(
        {"created_at": datetime.now(timezone.utc).isoformat(), "files": manifest,
         "excluded": EXCLUDE, "scanned_for": sorted(LEAKS)}, indent=1))
    zip_path = dest.with_suffix(".zip")
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as z:
        for f in sorted(dest.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(dest.parent).as_posix())
    size = sum(f.stat().st_size for f in dest.rglob("*") if f.is_file())
    print(f"exported {len(files)} files ({size / 1e6:.1f} MB) -> {dest}\nzip: {zip_path} "
          f"({zip_path.stat().st_size / 1e6:.1f} MB); leak scan: clean "
          f"({len(allowed)} e-mail addresses allowed because they are printed in the source agreement)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
